#!/usr/bin/env bash
# Builds the installable jar:  tools/build.sh 1.2.0
# Needs: JDK 17+ (javac, jar, jdeps), python3, and Jira's API jars in ./lib (see tools/collect-jira-api.sh).
set -euo pipefail
VERSION="${1:?usage: tools/build.sh <version>}"
B="$(cd "$(dirname "$0")/.." && pwd)"
API="${JIRA_API_DIR:-$B/lib}"
ls "$API"/jira-api-*.jar >/dev/null 2>&1 || { echo "Jira API jars not found in $API — run tools/collect-jira-api.sh first" >&2; exit 1; }
OUT="$B/build"
rm -rf "$OUT"; mkdir -p "$OUT/classes" "$OUT/jar"

# 1. generated sources and assets
mkdir -p "$B/java/gen/ir/arasstech/persian"
cat > "$B/java/gen/ir/arasstech/persian/Version.java" <<EOF
package ir.arasstech.persian;

/** Generated by tools/build.sh */
final class Version {
    static final String VALUE = "$VERSION";
    private Version() { }
}
EOF
python3 - "$VERSION" "$B" <<'PY'
import sys, json, re
v = sys.argv[1]
B = sys.argv[2]
d = open(B + '/i18n/dict.min.json', encoding='utf-8').read().strip()
t = open(B + '/atp-admin.js.tpl', encoding='utf-8').read()
assert '__DICT__' in t
t = t.replace('__DICT__', d)
t = re.sub(r'settings page v[0-9.]+', 'settings page v' + v, t)
open(B + '/src/admin/atp-admin.js', 'w', encoding='utf-8').write(t)
for f in ['src/js/atp-boot.js', 'src/js/atp-dates.js', 'src/js/atp-mirror.js', 'src/css/atp-rtl.css']:
    p = B + '/' + f
    s = open(p, encoding='utf-8').read()
    s2 = re.sub(r'(\*! Arass Tech Persian[^*]*?· )v[0-9.]+', r'\g<1>v' + v, s, count=1)
    s2 = re.sub(r"(setAttribute\('data-atp', ')[0-9.]+('\))", r'\g<1>' + v + r'\g<2>', s2)
    s2 = re.sub(r"(ATP\.version = ')[0-9.]+(')", r'\g<1>' + v + r'\g<2>', s2)
    open(p, 'w', encoding='utf-8').write(s2)
x = open(B + '/src/atlassian-plugin.xml', encoding='utf-8').read()
x = re.sub(r'<version>[^<]+</version>', '<version>' + v + '</version>', x, count=1)
open(B + '/src/atlassian-plugin.xml', 'w', encoding='utf-8').write(x)
PY

# 2. compile against the exact API jars of Jira 10.3 (Java 17 bytecode, as Jira 10 runs on 17/21)
CP=$(ls "$API"/*.jar | tr '\n' ':')
javac --release 17 -encoding UTF-8 -Xlint:all,-serial,-processing -cp "$CP" -d "$OUT/classes" \
  $(find "$B/java/src" "$B/java/gen" -name '*.java')

# 3. assemble
cp -r "$B/src/." "$OUT/jar/"
rm -rf "$OUT/jar/META-INF/MANIFEST.MF"
cp -r "$B/meta/META-INF/." "$OUT/jar/META-INF/"
cp -r "$OUT/classes/." "$OUT/jar/"
( cd "$OUT/jar" && find . -name '*_fa_IR.properties' | sed 's|^\./||' | sort > atp-i18n-index.txt )
IMPORTS=$(jdeps --multi-release 17 -verbose:package -cp "$CP" "$OUT/classes" 2>/dev/null \
  | awk '$1 ~ /^ir\.arasstech/ && $3 !~ /^(java\.|javax\.annotation|ir\.arasstech)/ {print $3}' | sort -u | grep -v '^java\.' || true)
IMP_LINE=$(for p in $IMPORTS; do printf '%s;resolution:=optional,' "$p"; done | sed 's/,$//')
python3 - "$VERSION" "$IMP_LINE" "$OUT/jar/META-INF/MANIFEST.MF" <<'PY'
import sys, textwrap
v, imports, path = sys.argv[1], sys.argv[2], sys.argv[3]
hdr = [
    ('Manifest-Version', '1.0'),
    ('Bundle-ManifestVersion', '2'),
    ('Bundle-SymbolicName', 'ir.arasstech.persian.jsm'),
    ('Bundle-Name', 'Arass Tech Persian for Jira Service Management'),
    ('Bundle-Version', v),
    ('Bundle-Vendor', 'Arass Tech'),
    ('Bundle-Description', 'Persian language, right-to-left layout and Jalali dates for Jira Service Management'),
    ('Atlassian-Plugin-Key', 'ir.arasstech.persian.jsm'),
    ('Spring-Context', '*'),
    ('Import-Package', imports),
    ('Created-By', 'Arass Tech'),
]
def line(k, val):
    s = (k + ': ' + val).encode('utf-8')
    out, first = [], True
    while s:
        n = 72 if first else 71
        out.append((b'' if first else b' ') + s[:n]); s = s[n:]; first = False
    return b'\r\n'.join(out) + b'\r\n'
open(path, 'wb').write(b''.join(line(k, v2) for k, v2 in hdr if v2) + b'\r\n')
PY
mkdir -p "$B/dist"
JAR="$B/dist/arasstech-persian-jsm-$VERSION.jar"
rm -f "$JAR"
( cd "$OUT/jar" && jar --create --file "$JAR" --manifest META-INF/MANIFEST.MF $(ls -A | grep -v '^META-INF$') META-INF/spring META-INF/plugin-components $(ls META-INF | grep -v -e MANIFEST.MF -e spring -e plugin-components | sed 's|^|META-INF/|') )
ls -l "$JAR"
echo "imports: $IMPORTS" | tr '\n' ' '; echo
